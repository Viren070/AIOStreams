import { createHash } from 'crypto';

/** With a seed, the same list always comes out in the same order. */
export function shuffled<T>(list: readonly T[], seed?: string): T[] {
  const random = seed === undefined ? Math.random : seeded(seed);
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** mulberry32 */
function seeded(seed: string): () => number {
  let state = createHash('sha1').update(seed).digest().readUInt32LE(0);
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
